# Các mốc dữ liệu tương ứng với tên file trong thư mục của bạn
MOCS = [
    {"moc": 1, "ngay": "2025-09-11", "prefix": "calendar2025-09-11"},
    {"moc": 2, "ngay": "2025-12-12", "prefix": "calendar2025-12-12"},
    {"moc": 3, "ngay": "2026-03-19", "prefix": "calendar2026-03-19"},
    {"moc": 4, "ngay": "2026-06-15", "prefix": "calendar2026-06-15"},
]

def find_file(prefix):
    """Tự động tìm đường dẫn file calendar trong thư mục data hoặc thư mục hiện tại"""
    paths_to_search = [
        f"data/{prefix}*",
        f"data/calendar/{prefix}*",
        f"calendar/{prefix}*",
        f"{prefix}*"
    ]
    for p in paths_to_search:
        files = glob.glob(p)
        if files:
            return files[0]
    return None

# ==========================================
# 2. KIỂM TRA DỮ LIỆU & TÍNH TOÁN
# ==========================================
def main():
    results = []
    
    for item in MOCS:
        moc_num = item["moc"]
        ngay = item["ngay"]
        prefix = item["prefix"]
        
        file_path = find_file(prefix)
        
        if not file_path:
            print(f"[X] Không tìm thấy tệp cho mốc {moc_num} ({ngay})")
            results.append({
                "moc": moc_num,
                "ngay": ngay,
                "tai_ve_ok": "404",
                "calendar_bytes": 0,
                "calendar_dong": 0
            })
            continue

        # Lấy kích thước byte tệp gốc
        bytes_size = os.path.getsize(file_path)
        
        try:
            df = pd.read_csv(file_path, low_memory=False)
            tai_ve_ok = "co"
        except Exception as e:
            print(f"[X] Lỗi đọc tệp mốc {moc_num}: {e}")
            results.append({
                "moc": moc_num,
                "ngay": ngay,
                "tai_ve_ok": "loi_doc_file",
                "calendar_bytes": bytes_size,
                "calendar_dong": 0
            })
            continue

        # Lọc dữ liệu theo ID phân công
        if ASSIGNED_LISTING_IDS:
            df_filtered = df[df['listing_id'].isin(ASSIGNED_LISTING_IDS)]
        else:
            df_filtered = df

        calendar_dong = len(df_filtered)
        
        results.append({
            "moc": moc_num,
            "ngay": ngay,
            "tai_ve_ok": tai_ve_ok,
            "calendar_bytes": bytes_size,
            "calendar_dong": calendar_dong
        })

    # ==========================================
    # 3. LƯU KẾT QUẢ VÀO FILE CSV TRONG THƯ MỤC REPORTS
    # ==========================================
    df_res = pd.DataFrame(results)
    
    print("\n==========================================")
    print("--- KẾT QUẢ KIỂM TRA TỆP CALENDAR ---")
    print("==========================================")
    print(df_res.to_string(index=False))

    # Tự động tạo thư mục reports/ nếu chưa có
    reports_dir = "reports"
    os.makedirs(reports_dir, exist_ok=True)
    
    # Đường dẫn xuất file csv
    output_csv_path = os.path.join(reports_dir, "check_calendar.csv")
    df_res.to_csv(output_csv_path, index=False)
    
    print(f"\n[V] Đã lưu file kết quả thành công vào: {output_csv_path}")

if __name__ == "__main__":
    main()